import { accessSync, constants, existsSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { creatorBuildArgs, normalizeCreatorBuildStatus, projectBlockers, readJsonIfPresent } from './creator-support.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const command = process.argv[2] ?? 'inspect';
const lock = readJsonIfPresent(join(root, 'configs/engine.lock.json'));
const candidates = new Set();
function executable(path) {
  try { accessSync(path, constants.X_OK); candidates.add(path); } catch { /* Not an installed executable. */ }
}
for (const path of [process.env.COCOS_CREATOR_CLI, process.env.COCOS_CREATOR,
  '/Applications/CocosCreator.app/Contents/MacOS/CocosCreator',
  join(homedir(), 'Applications/CocosCreator.app/Contents/MacOS/CocosCreator')]) {
  if (path) executable(resolve(path));
}
function findCreator(directory, depth) {
  if (!existsSync(directory) || depth < 0) return;
  for (const entry of readdirSync(directory, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const path = join(directory, entry.name);
    if (entry.name === 'CocosCreator.app') executable(join(path, 'Contents/MacOS/CocosCreator'));
    else if (!entry.name.endsWith('.app')) findCreator(path, depth - 1);
  }
}
for (const directory of ['/Applications/Cocos', '/Applications/CocosCreator', join(homedir(), 'CocosDashboard'), join(homedir(), 'Cocos')]) {
  findCreator(directory, 5);
}

function blocked(messages) {
  for (const message of messages) console.error(`BLOCKED: ${message}`);
  console.error('解除步骤见 docs/EDITOR_SETUP.md；不要伪造版本、scene/meta 或导入证据。');
  process.exitCode = 2;
}

try {
  if (command === 'inspect') {
    console.log(JSON.stringify({
      projectRoot: root, nodeVersion: process.version, engineFamily: 'Cocos Creator', requiredSeries: '3.8',
      lockedPatch: lock?.patch ?? null, requestedPhysicsBackend: 'Box2D 2D',
      detectedExecutables: [...candidates], projectBlockers: projectBlockers(root, { requireScene: true }),
      editorImportVerified: lock?.editorImportVerified === true, webBuildVerified: lock?.webBuildVerified === true,
    }, null, 2));
  } else if (command === 'typecheck') {
    const blockers = projectBlockers(root);
    if (blockers.length) blocked(blockers);
    else {
      // No cc stubs: use the declarations actually generated by this project's editor import.
      const result = spawnSync(process.execPath, [join(root, 'node_modules/typescript/bin/tsc'), '--project', join(root, 'tsconfig.creator.json'), '--noEmit'], { cwd: root, stdio: 'inherit' });
      if (result.error) throw result.error;
      process.exitCode = result.status ?? 1;
    }
  } else if (command === 'build-web') {
    const blockers = projectBlockers(root, { requireScene: true });
    const creator = [...candidates][0];
    if (!creator) blockers.push('未发现 Creator 可执行文件，设置 COCOS_CREATOR_CLI 可指定非标准安装路径');
    if (blockers.length) blocked(blockers);
    else {
      // Verify the installed application version before asking it to open/migrate the project.
      const plist = resolve(creator, '../../Info.plist');
      if (!existsSync(plist)) {
        blocked(['无法读取所选 Creator 的 Info.plist 版本；当前自动构建适配器只验证 macOS .app 路径']);
      } else {
        const version = spawnSync('/usr/bin/plutil', ['-extract', 'CFBundleShortVersionString', 'raw', plist], { encoding: 'utf8' });
        if (version.status !== 0 || version.stdout.trim() !== lock.patch) {
          blocked([`所选编辑器版本 ${version.stdout?.trim() || '未知'} 与锁定版本 ${lock.patch} 不一致`]);
        } else {
          const meta = readJsonIfPresent(join(root, 'assets/scenes/Boot.scene.meta'));
          const args = creatorBuildArgs(root, meta.uuid);
          console.log(JSON.stringify({ creator, args, configuredPatch: lock.patch }));
          const result = spawnSync(creator, args, { cwd: root, stdio: 'inherit' });
          if (result.error) throw result.error;
          console.log(`Creator raw exit code: ${result.status}`);
          process.exitCode = normalizeCreatorBuildStatus(result.status);
          if (process.exitCode === 0 && !existsSync(join(root, 'build/web-desktop/index.html'))) {
            throw new Error('Creator 返回构建成功码，但未找到预期的 build/web-desktop/index.html；需核对实际构建配置');
          }
          // Deliberately do not set webBuildVerified: opening the output in WebGL is still a separate check.
        }
      }
    }
  } else throw new Error(`未知环境命令：${command}`);
} catch (error) {
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
}
